def paste(filename,x,y,maxw,maxh,crop=False):
    art=Gimp.file_load(Gimp.RunMode.NONINTERACTIVE,Gio.File.new_for_path(str(root/'preview'/filename)))
    if crop:art.crop(2300,810,50,210)
    k=min(maxw/art.get_width(),maxh/art.get_height());w,h=round(k*art.get_width()),round(k*art.get_height());art.scale(w,h)
    l=Gimp.Layer.new_from_visible(art,im,filename);im.insert_layer(l,None,0);l.set_offsets(x+(maxw-w)//2,y+(maxh-h)//2);art.delete()
